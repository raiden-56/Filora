export const TOOL_BY_SLUG: Record<string, ToolDefinition> = Object.fromEntries(TOOLS.map((t) => [t.slug, t]));
export const TOOL_BY_ID: Record<string, ToolDefinition> = Object.fromEntries(TOOLS.map((t) => [t.id, t]));
export const CATEGORY_BY_ID: Record<ToolCategoryId, ToolCategory> = Object.fromEntries(
  CATEGORIES.map((c) => [c.id, c]),
) as Record<ToolCategoryId, ToolCategory>;
export const CATEGORY_BY_SLUG: Record<string, ToolCategory> = Object.fromEntries(CATEGORIES.map((c) => [c.slug, c]));

export function toolsInCategory(id: ToolCategoryId): ToolDefinition[] {
  return TOOLS.filter((t) => t.category === id);
}

export function toolPath(tool: ToolDefinition | string): string {
  const slug = typeof tool === 'string' ? tool : tool.slug;
  return `/tools/${slug}`;
}

export function categoryPath(cat: ToolCategory | ToolCategoryId): string {
  const c = typeof cat === 'string' ? CATEGORY_BY_ID[cat] : cat;
  return `/${c.slug}`;
}

